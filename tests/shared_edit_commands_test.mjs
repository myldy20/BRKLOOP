// Isolated canonical edit command tests. This test does not import or modify BRKLOOP's shipping UI.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {createResearchEditSession} from '../research/shared-edit-commands.mjs';
const html=readFileSync('web/editor.html','utf8');
const E=vm.runInNewContext(html.slice(html.indexOf('/*PROTO-BEGIN*/'),html.indexOf('/*PROTO-END*/'))+';({makeMockDevice,previewSnapshot})',
  {setTimeout,clearTimeout,setInterval,clearInterval,console,TextEncoder,TextDecoder,Blob,Response,DecompressionStream});
const m=E.makeMockDevice({auto:false});
try{
  const original=E.previewSnapshot(m.state);
  const initial=JSON.stringify(original);
  const s=createResearchEditSession(original);
  const start=JSON.stringify(s.getState());
  s.select(0,0);
  s.setMode('roll');s.setMode('step');
  assert.equal(JSON.stringify(s.getState()),start,'Editor mode/selection cannot edit project data');
  assert.equal(s.history().undo,0);
  const first={type:'writeChord',track:0,step:0,notes:[60,64,67]};
  assert.equal(s.dispatch(first),true);
  assert.deepEqual(s.getState().tracks[0].step[0].notes.slice(0,3),[60,64,67]);
  assert.equal(s.history().undo,1,'Chord insertion is one undo command');
  assert.equal(s.dispatch({type:'addNote',track:0,step:0,note:72}),true);
  assert.throws(()=>s.dispatch({type:'addNote',track:0,step:0,note:74}),/1..4 notes/);
  assert.equal(s.getState().tracks[0].step[0].n,4,'A rejected fifth note changes nothing');
  assert.equal(s.history().undo,2);
  assert.equal(s.undo(),true);
  assert.equal(s.getState().tracks[0].step[0].n,3);
  assert.equal(s.redo(),true);
  assert.equal(s.getState().tracks[0].step[0].n,4);
  assert.equal(s.undo(),true);
  s.dispatch({type:'setMicro',track:0,step:0,value:-12});
  assert.equal(s.history().redo,0,'New action invalidates redo');
  s.dispatch({type:'setFill',track:0,step:0,value:2});
  s.dispatch({type:'setLock',track:0,step:0,param:5,value:74});
  const tracked=s.getState().tracks[0];
  assert.equal(tracked.micro[0],-12);
  assert.equal(tracked.fill[0]&3,2);
  assert.deepEqual(JSON.parse(JSON.stringify(tracked.locks)),[{step:0,param:5,value:74}]);
  s.dispatch({type:'writeNote',track:0,step:0,note:69});
  assert.equal(s.getState().tracks[0].step[0].notes[0],69);
  assert.equal(s.getState().tracks[0].micro[0],-12,'Pitch changes must not reset micro');
  assert.equal(s.getState().tracks[0].fill[0]&3,2,'Pitch changes must not reset fill');
  assert.equal(s.getState().tracks[0].locks.length,1,'Pitch changes must not erase native locks');
  s.dispatch({type:'setLength',track:0,length:64});
  s.dispatch({type:'writeNote',track:0,step:63,note:85});
  s.dispatch({type:'setLength',track:0,length:16});
  assert.throws(()=>s.dispatch({type:'writeNote',track:0,step:63,note:86}),/outside active LEN/);
  s.dispatch({type:'setLength',track:0,length:64});
  assert.equal(s.getState().tracks[0].step[63].notes[0],85,'Shorten/extend must not discard hidden steps');
  assert.throws(()=>s.dispatch({type:'setLength',track:0,length:65}),RangeError);
  assert.throws(()=>s.dispatch({type:'setDivision',track:0,division:9}),RangeError);
  s.select(0,63);s.setMode('roll');
  assert.equal(s.getView().step,63);
  // Native SF_CONT continuity bits, per-note LVL/RAT move with pitch identities.
  const snap=s.getState(),st=snap.tracks[1].step[0];
  st.n=3;st.notes=[60,64,67,0];st.time=0;st.flags=1 | (8<<1);st.lvl=(1<<0)|(2<<2)|(3<<4);
  st.rat=(2<<0)|(1<<2);
  const sx=createResearchEditSession(snap);
  sx.dispatch({type:'writeChord',track:1,step:0,notes:[67,64,72]});
  const remap=sx.getState().tracks[1].step[0];
  assert.deepEqual(remap.notes.slice(0,3),[67,64,72]);
  assert.equal((remap.flags&8)!==0,false);
  assert.equal((remap.flags&16)!==0,true,'Continuation follows note 64, now slot 1');
  assert.equal(remap.lvl,(3<<0)|(2<<2),'Per-note dynamics follow note identity');
  assert.equal(remap.rat,1<<2,'Per-note ratchet follows note identity');
  sx.dispatch({type:'removeNote',track:1,step:0,note:67});
  assert.equal(sx.getState().tracks[1].step[0].notes[0],64);
  assert.equal(sx.getState().tracks[1].step[0].flags&8,8,'Continuation flag shifts with removed note');
  sx.dispatch({type:'clearNotes',track:1,step:0});
  assert.equal(sx.getState().tracks[1].step[0].time,2);
  assert.equal(sx.getState().tracks[1].step[0].n,2,'REST retains the underlying note data');
  const drum=s.getState().tracks[3].dstep[31];
  s.dispatch({type:'setLength',track:3,length:64});
  s.dispatch({type:'toggleDrumHit',track:3,step:31,lane:13});
  s.dispatch({type:'setDrumLevel',track:3,step:31,lane:13,value:3});
  s.dispatch({type:'setDrumRatchet',track:3,step:31,lane:13,value:2});
  const dr=s.getState().tracks[3].dstep[31];
  assert(dr.on&(1<<13));assert.equal(dr.lvl[13],3);assert.equal(dr.rat[13],2);
  assert.equal(dr.lvl[0],drum.lvl[0],'Editing one lane keeps other 15 untouched');
  s.dispatch({type:'setMicro',track:3,step:31,value:6});
  assert.equal(s.getState().tracks[3].micro[31],6,'Drum micro is a column field');
  const before=s.getState(),v=before.tracks[0].step[0].notes[0];
  before.tracks[0].step[0].notes[0]=99;
  assert.equal(s.getState().tracks[0].step[0].notes[0],v,'External readers must not mutate session');
  assert.equal(JSON.stringify(original),initial,'Research edits must not mutate the SLOOP starting snapshot');
  console.log('PASS isolated shared STEP/ROLL canonical edit commands, chord expression, 64-step preservation and undo');
}finally{m.stop();}
